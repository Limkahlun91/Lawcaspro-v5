  HR_EMPLOYEE_HAS_PENDING_HANDOVER: "HR_EMPLOYEE_HAS_PENDING_HANDOVER",
  HR_CROSS_FIRM_ACCESS_DENIED: "HR_CROSS_FIRM_ACCESS_DENIED",
  HR_METHOD_NOT_ALLOWED: "HR_METHOD_NOT_ALLOWED",
  HR_DOCUMENT_PERMISSION_DENIED: "HR_DOCUMENT_PERMISSION_DENIED",
